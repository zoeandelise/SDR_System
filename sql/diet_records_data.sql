SELECT 
    '按餐次统计' as '统计项目',
    CONCAT(
        '早餐:', SUM(CASE WHEN meal_type = '0' THEN 1 ELSE 0 END), '条, ',
        '午餐:', SUM(CASE WHEN meal_type = '1' THEN 1 ELSE 0 END), '条, ',
        '晚餐:', SUM(CASE WHEN meal_type = '2' THEN 1 ELSE 0 END), '条, ',
        '加餐:', SUM(CASE WHEN meal_type = '3' THEN 1 ELSE 0 END), '条'
    ) as '数量'
FROM diet_record 
